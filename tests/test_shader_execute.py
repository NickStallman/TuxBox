"""The execute stage binds what a translation declares, seeds it alike for both builds and sorts outcomes."""
import struct
import unittest

from project_tuxbox import shader_execute as execute

PROGRAM = """// Generated by tuxbox-xshader
struct TbElem_ubuf18 { uint w[3]; };
cbuffer CB22 : register(b22, space1) { uint4 cb22[2]; };
cbuffer TBIndex0_1 : register(b3, space2) { uint tb_index0_1; };
Texture2D<float4> tex191 : register(t191, space1);
TextureCube<float4> tex4 : register(t4);
Texture2DArray<float4> tex5[4] : register(t5, space1);
Buffer<int2> stb339 : register(t339, space1);
ByteAddressBuffer raw_sbuf3 : register(t3);
SamplerState samp3 : register(s3, space1);
SamplerComparisonState scmp4 : register(s4, space1);
RWTexture2D<uint> uav31 : register(u31, space1);
RWStructuredBuffer<TbElem_ubuf18> ubuf18 : register(u18, space1);
RWBuffer<float> utb17 : register(u17);
[WaveSize(64)]
[numthreads(8, 8, 1)]
void main(uint3 gid : SV_GroupID) {
    // register(t9) in a comment is not a declaration
}
"""


class Bindings(unittest.TestCase):
    def test_every_declared_resource_is_bound_in_order(self):
        found = execute.bindings(PROGRAM)
        self.assertEqual([(b.kind, b.register, b.space) for b in found], [
            ("cbv", "b22", 1), ("cbv", "b3", 2), ("srv_tex", "t191", 1), ("srv_tex", "t4", 0),
            ("srv_tex", "t5", 1), ("srv_typed", "t339", 1), ("srv_raw", "t3", 0), ("sampler", "s3", 1),
            ("sampler_cmp", "s4", 1), ("uav_tex", "u31", 1), ("uav_struct", "u18", 1), ("uav_typed", "u17", 0)])
        by = {b.register: b for b in found}
        self.assertEqual(by["b22"].width, 256)
        self.assertEqual((by["t4"].dimension, by["t4"].depth), ("cube", 6))
        self.assertEqual((by["t5"].count, by["t5"].dimension), (4, "2darray"))
        self.assertEqual((by["t339"].format, by["t339"].family), (18, "sint"))
        self.assertEqual((by["u31"].format, by["u31"].family), (42, "uint"))
        self.assertEqual(by["u18"].stride, 12)
        self.assertEqual(by["u17"].format, 41)

    def test_the_root_signature_puts_views_then_samplers_in_tables(self):
        root = execute.root_signature(execute.bindings(PROGRAM))
        self.assertTrue(root.startswith("RootFlags(0), DescriptorTable(CBV(b22, space=1, numDescriptors=1), "))
        self.assertIn("SRV(t5, space=1, numDescriptors=4)", root)
        self.assertTrue(root.endswith("DescriptorTable(Sampler(s3, space=1, numDescriptors=1), "
                                      "Sampler(s4, space=1, numDescriptors=1))"))
        self.assertTrue(execute.with_root_signature(PROGRAM, execute.bindings(PROGRAM))
                        .startswith('#define TB_EXECUTE_ROOT "RootFlags(0), '))
        self.assertEqual(execute.wave_size(PROGRAM), 64)

    def test_programs_the_runner_cant_feed_are_skipped_with_a_reason(self):
        writable = "RWByteAddressBuffer out : register(u0);\n"
        cases = {
            "indexes the descriptor heap directly": writable + "Texture2D t = ResourceDescriptorHeap[s4];\n",
            "unbounded descriptor array": writable + "Texture2D<float4> all[] : register(t0, space9);\n",
            "reads a ray tracing scene": writable + "RaytracingAccelerationStructure s : register(t1);\n",
            "Texture2DMS resources": writable + "Texture2DMS<float4> m : register(t2);\n",
            "writes no resource the runner can read back": "Texture2D<float4> t : register(t0);\n",
            "constant buffer member that isn't a word or word vector":
                writable + "cbuffer C : register(b0) { MyStruct s; };\n",
        }
        for reason, hlsl in cases.items():
            with self.subTest(reason), self.assertRaises(execute.Unsupported) as raised:
                execute.bindings(hlsl)
            self.assertEqual(str(raised.exception), reason)
        with self.assertRaises(execute.Unsupported) as raised:
            execute.bindings(writable + "Texture2D<float4> t : register(t0) : something;\n")
        self.assertTrue(str(raised.exception).startswith("declaration the runner can't bind"))


class Seeds(unittest.TestCase):
    def test_both_builds_get_the_same_inputs_and_requests_differ(self):
        found = execute.bindings(PROGRAM)
        first = execute.case_files("c00000b", "request.dxbc", found)
        second = execute.case_files("c00000a", "request.dxbc", found)
        other = execute.case_files("c00000b", "other.dxbc", found)
        seeds = sorted(name for name in first if name.endswith(".seed"))
        self.assertEqual(len(seeds), 1 + 1 + 1 + 1 + 4 + 1 + 1 + 1 + 1 + 1)  # samplers have none; t5 has four
        for name in seeds:
            self.assertEqual(first[name], second[name.replace("c00000b", "c00000a")])
        self.assertNotEqual(first["c00000b.r2.e0.seed"], other["c00000b.r2.e0.seed"])
        self.assertNotEqual(first["c00000b.r4.e0.seed"], first["c00000b.r4.e1.seed"])
        self.assertEqual(first["c00000b.bind"].decode().splitlines()[2], "srv_tex 2d 2 1 32 32 1 0")
        self.assertEqual(first["c00000b.grid"], b"2 2 1\n")
        self.assertNotIn("c00000b.minwave", first)
        self.assertEqual(execute.case_files("x", "k", found, minwave=64)["x.minwave"], b"64\n")

    def test_seeded_values_stay_small(self):
        for family, limit in (("float", None), ("uint", 256), ("sint", 256), ("mixed", None)):
            binding = execute.Binding("srv_raw", "t0", 0, width=4096, family=family)
            data = execute.seeded("key", binding, 0)
            self.assertEqual(len(data), 4096)
            for word in struct.unpack("<1024I", data):
                value = struct.unpack("<f", struct.pack("<I", word))[0]
                small_int = word < (limit or 32)
                self.assertTrue(small_int or 0 < value < 4, (family, hex(word)))
                if family == "float":
                    self.assertTrue(word == 0 or 0 < value < 4)


class Receipts(unittest.TestCase):
    NAMES = ["a", "b", "c", "d", "e"]

    def test_outcomes_and_a_hang_that_stops_the_runner(self):
        text = "adapter=10de:2786\nwave_lanes_max=32\nbegin=a\na_ok=1\nbegin=b\nb_error=compute pipeline failed: 0x80070057\n" \
               "c_skipped=needs 64-lane waves\nbegin=d\n"
        outcomes, pending, fields = execute.receipt(text, self.NAMES)
        self.assertEqual(outcomes, {"a": ("ran", ""), "b": ("failed", "compute pipeline failed: 0x80070057"),
                                    "c": ("skipped", "needs 64-lane waves"), "d": ("hang", "GPU work did not finish")})
        self.assertEqual(pending, ["e"])
        self.assertEqual(fields["wave_lanes_max"], "32")

    def test_a_reported_hang(self):
        outcomes, pending, _ = execute.receipt("begin=a\na_hang=1\n", self.NAMES)
        self.assertEqual(outcomes, {"a": ("hang", "GPU work did not finish")})
        self.assertEqual(pending, self.NAMES[1:])

    def test_a_runner_that_never_started_leaves_everything_pending(self):
        outcomes, pending, fields = execute.receipt("error=device failed: 0x887a0004\n", self.NAMES)
        self.assertEqual((outcomes, pending, fields["error"]), ({}, self.NAMES, "device failed: 0x887a0004"))


class Outputs(unittest.TestCase):
    def test_the_digest_covers_every_writable_element(self):
        found = [execute.Binding("srv_raw", "t0", 0, width=16), execute.Binding("uav_raw", "u0", 0, width=16, count=2)]
        files = {"n.u1.e0.bin": b"\1" * 16, "n.u1.e1.bin": b"\2" * 16}
        first = execute.output_digest(files.__getitem__, "n", found)
        files["n.u1.e1.bin"] = b"\3" * 16
        self.assertNotEqual(first, execute.output_digest(files.__getitem__, "n", found))
        seeds = {"n.r1.e0.seed": b"\1" * 16, "n.r1.e1.seed": b"\3" * 16}
        self.assertFalse(execute.wrote(files.__getitem__, seeds.__getitem__, "n", found))
        seeds["n.r1.e1.seed"] = b"\0" * 16
        self.assertTrue(execute.wrote(files.__getitem__, seeds.__getitem__, "n", found))


def ran(digest, hlsl):
    return {"status": "ran", "digest": digest, "hlsl": hlsl}


class Compare(unittest.TestCase):
    def test_every_kind_is_named_and_only_changes_and_losses_block(self):
        before = {"same": ran("1", "x"), "equivalent": ran("1", "x"), "changed": ran("1", "x"), "unstable": ran("1", "x"),
                  "lost": ran("1", "x"), "gained": {"status": "refused", "reason": "translator refused"},
                  "neither": {"status": "skipped", "reason": "indexes the descriptor heap directly"}}
        after = {"same": ran("1", "x"), "equivalent": ran("1", "y"), "changed": ran("2", "y"), "unstable": ran("2", "x"),
                 "lost": {"status": "hang", "reason": "GPU work did not finish"}, "gained": ran("1", "y"),
                 "neither": {"status": "skipped", "reason": "indexes the descriptor heap directly"}}
        kinds = execute.compare(before, after)
        self.assertEqual(kinds, {kind: [kind] for kind in kinds})
        problems = execute.blocking(kinds)
        self.assertEqual(len(problems), 2)
        self.assertIn("compute different results, e.g. changed", problems[0])
        self.assertIn("no longer run, e.g. lost", problems[1])
        self.assertEqual(execute.blocking(execute.compare(before, before)), [])

    def test_a_baseline_that_disagrees_with_itself_is_unstable_not_changed(self):
        before, after = {"r": ran("1", "x"), "s": ran("1", "x")}, {"r": ran("2", "y"), "s": ran("2", "y")}
        repeat = {"r": ran("3", "x"), "s": ran("1", "x")}
        kinds = execute.compare(before, after, repeat)
        self.assertEqual((kinds["unstable"], kinds["changed"]), (["r"], ["s"]))
        hung = {"status": "hang", "reason": "GPU work did not finish"}
        kinds = execute.compare({"t": ran("1", "x")}, {"t": hung}, {"t": hung})
        self.assertEqual((kinds["unstable"], kinds["lost"]), (["t"], []))

    def test_reasons_group_by_kind(self):
        outcomes = {"a": {"status": "skipped", "reason": "translation over 1024 KiB"},
                    "b": {"status": "skipped", "reason": "translation over 1024 KiB"},
                    "c": {"status": "failed", "reason": "compute pipeline failed: 0x80070057"}, "d": ran("1", "x")}
        self.assertEqual(execute.reasons(outcomes), [("skipped: translation over N KiB", 2),
                                                     ("failed: compute pipeline failed: N", 1)])


if __name__ == "__main__":
    unittest.main()
