"""Write src/tables/*.rs from bcpack-rs's table files.

Usage: python gen_tables.py path/to/bcpack-rs/data src/tables

The inputs are data/bc1_window.json, bc1_quad_table.json, bc3.json, bc4.json,
bc5.json and bc7.json of https://github.com/Ahmet-Dedeler/bcpack-rs at
REVISION. Only their values are used. See docs/REFERENCES.md#storage-codec-attribution
for where bcpack-rs says each table came from.
"""
import hashlib
import json
import os
import sys

REVISION = "2d6333b03af4eaa33b2cffe9a8ab0439424955dd"
FILES = ("bc1_window.json", "bc1_quad_table.json", "bc3.json", "bc4.json", "bc5.json", "bc7.json")


def header(sources, digests, what):
    lines = [
        "// bcpack-rs by Ahmet Dedeler (https://github.com/Ahmet-Dedeler, https://ahmetdedeler.com)",
        "// Source: https://github.com/Ahmet-Dedeler/bcpack-rs",
        "// SPDX-License-Identifier: MIT OR Apache-2.0",
        "// If you copy, vendor or port this file, keep this header and credit bcpack-rs in your README.",
        "//",
        f"// Generated by gen_tables.py from bcpack-rs {REVISION}:",
    ]
    lines += [f"// data/{s} (SHA-256 {digests[s]})" for s in sources]
    lines += ["// Values only. Do not edit by hand.", f"//! {what}"]
    return "\n".join(lines) + "\n"


def row(values):
    return "[" + ", ".join(str(v) for v in values) + "]"


def check(values, bits):
    assert all(0 <= v < 1 << b for v, b in zip(values, bits)), (values, bits)


def main(data, out):
    raw = {f: open(os.path.join(data, f), "rb").read() for f in FILES}
    digests = {f: hashlib.sha256(raw[f]).hexdigest() for f in FILES}
    tables = {f: json.loads(raw[f]) for f in FILES}

    # BC1: the 255-entry dictionary is read as window slot (i - d) mod 256.
    slots = tables["bc1_window.json"]["slots"]
    assert len(slots) == 256 and slots[0] is None and all(s is not None for s in slots[1:])
    codes = [None] * 256
    for e in tables["bc1_quad_table.json"]["entries"]:
        assert codes[e["sym"]] is None
        codes[e["sym"]] = e["codes"]
    assert all(c is not None for c in codes)
    # bcpack-rs lists four mirror pairs of its fitted codebook as uncertain.
    # Two of them are swapped relative to the format's table (as VIctory's
    # bcpack-tables.bin carries it, observed through its decoder's output on
    # 400 retail BC1 chunks): symbols 229/235 and 247/248.
    for a, b in ((229, 235), (247, 248)):
        codes[a], codes[b] = codes[b], codes[a]
    text = header(("bc1_window.json", "bc1_quad_table.json"), digests,
                  "BC1: the endpoint window and the quadrant codebook.")
    text += "\n/// Endpoint fields R0 G0 B0 R1 G1 B1 read by a reference before the first\n"
    text += "/// block, by slot `(i - d) mod 256`. Slot 0 is never read.\n#[rustfmt::skip]\n"
    text += "pub const WINDOW: [[u8; 6]; 256] = [\n    [0, 0, 0, 0, 0, 0],\n"
    for s in slots[1:]:
        check(s["value"], (5, 6, 5, 5, 6, 5))
        text += f"    {row(s['value'])},\n"
    text += "];\n\n/// BC1 codes of a 2x2 group (TL, TR, BL, BR) per index-lane symbol.\n#[rustfmt::skip]\n"
    text += "pub const QUADS: [[u8; 4]; 256] = [\n"
    for s in range(0, 256, 8):
        text += "    " + " ".join(row(codes[k]) + "," for k in range(s, s + 8)) + "\n"
    text += "];\n"
    open(os.path.join(out, "bc1.rs"), "w").write(text)

    # BC3, BC4, BC5: pair ranks, BC3's quadrant ranks, the dictionaries.
    for name, ep_bits, ix_count in (("bc3", (8, 8, 5, 6, 5, 5, 6, 5), 32), ("bc4", (8, 8), 16), ("bc5", (8, 8, 8, 8), 32)):
        t = tables[f"{name}.json"]
        text = header((f"{name}.json",), digests, f"{name.upper()}: rank tables and the dictionary.")
        text += "\n/// Position residuals of the two pixels of a 3-bit index symbol.\n#[rustfmt::skip]\n"
        text += "pub const PAIRS: [[u8; 2]; 64] = [\n"
        assert len(t["pairs"]) == 64
        for s in range(0, 64, 8):
            text += "    " + " ".join(row(p) + "," for p in t["pairs"][s:s + 8]) + "\n"
        text += "];\n"
        if name == "bc3":
            assert len(t["quads"]) == 256
            text += "\n/// Colour position residuals of a 2x2 group (TL, TR, BL, BR) per symbol.\n#[rustfmt::skip]\n"
            text += "pub const QUADS: [[u8; 4]; 256] = [\n"
            for s in range(0, 256, 8):
                text += "    " + " ".join(row(q) + "," for q in t["quads"][s:s + 8]) + "\n"
            text += "];\n"
        ix_bits = [3] * 16 + ([2] * 16 if name == "bc3" else [3] * 16)
        text += "\n/// Endpoint fields and index positions of entries 0-254 (blocks -1 to -255).\n#[rustfmt::skip]\n"
        text += f"pub const DICTIONARY: [([u8; {len(ep_bits)}], [u8; {ix_count}]); 255] = [\n"
        assert len(t["dictionary"]) == 255
        for e in t["dictionary"]:
            check(e["ep"], ep_bits)
            check(e["ix"], ix_bits[:ix_count])
            assert len(e["ep"]) == len(ep_bits) and len(e["ix"]) == ix_count
            text += f"    ({row(e['ep'])}, {row(e['ix'])}),\n"
        text += "];\n"
        open(os.path.join(out, f"{name}.rs"), "w").write(text)

    # BC7: control codes and the dictionary.
    t = tables["bc7.json"]
    text = header(("bc7.json",), digests, "BC7: the control codes and the dictionary.")
    text += "\n/// Lane-15 symbols E and O, then mode, partition, rotation, index selection.\n#[rustfmt::skip]\n"
    text += f"pub const CONTROLS: [[u8; 6]; {len(t['control'])}] = [\n"
    for s in range(0, len(t["control"]), 6):
        text += "    " + " ".join(row(c) + "," for c in t["control"][s:s + 6]) + "\n"
    text += "];\n\n/// Subsets, endpoints (per subset R0 R1 G0 G1 B0 B1 A0 A1, 8-bit, top-aligned)\n"
    text += "/// and two index sets (4-bit, top-aligned) of entries 0-254.\n#[rustfmt::skip]\n"
    text += "pub const DICTIONARY: [(u8, [u8; 24], [u8; 32]); 255] = [\n"
    for e in t["dictionary"]:
        assert e["subsets"] in (1, 2, 3) and min(e["ep_bits"]) == 8 and min(e["ix_bits"]) == 4
        check(e["ep"], [8] * 24)
        check(e["ix"], [4] * 32)
        text += f"    ({e['subsets']}, {row(e['ep'])}, {row(e['ix'])}),\n"
    text += "];\n"
    open(os.path.join(out, "bc7.rs"), "w").write(text)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
