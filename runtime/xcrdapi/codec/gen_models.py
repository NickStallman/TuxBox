"""Write src/models.rs from Microsoft's silicon-rans `mdu_minirans.v`.

Usage: python gen_models.py path/to/mdu_minirans.v > src/models.rs

Only `freq_table` is read. The other tables of the Verilog (base, reciprocal,
shift and offset) follow from it, and the tests check that the decoder's exact
division matches the reciprocal path.
"""
import hashlib
import re
import sys

REVISION = "2f6827d8a4e6a78029c372f20d8b61f7cd408fc5"


def main(path):
    source = open(path, encoding="ascii").read()
    match = re.search(r"assign freq_table = '\{(.*?)\}; // end freq_table", source, re.S)
    if not match:
        sys.exit("freq_table not found")
    numbers = [int(n) for n in re.findall(r"\d+", re.sub(r"//[^\n]*", "", match.group(1)))]
    if len(numbers) != 9 * 16 * 10:
        sys.exit(f"freq_table has {len(numbers)} values, expected 1440")
    digest = hashlib.sha256(source.encode("ascii")).hexdigest()
    print(f"""// Generated by gen_models.py from mdu_minirans.v of
// https://github.com/microsoft/silicon-rans at {REVISION}
// (file SHA-256 {digest}). Do not edit by hand.
//
// The values are Microsoft's and are used under the MIT License:
// Copyright (c) Microsoft Corporation. See docs/licenses/silicon-rans/MIT.txt.
//! The 9 x 16 probability models of the MDU rANS decoder: for alphabets of
//! 1 to 9 bits, 16 models each, the per-symbol frequency of each segment.
use crate::rans::{{Model, Models}};

/// `FREQ[bits - 1][model]`: segments 0 to `bits` are used, the rest are 0.
#[rustfmt::skip]
pub const FREQ: [[[u16; 10]; 16]; 9] = [""")
    for width in range(9):
        print(f"    // {width + 1}-bit alphabet")
        print("    [")
        for model in range(16):
            row = numbers[(width * 16 + model) * 10:(width * 16 + model) * 10 + 10]
            print("        [" + ", ".join(str(v) for v in row) + "],")
        print("    ],")
    print("""];

/// Every model of the hardware decoder.
pub fn silicon_rans() -> Models {
    let mut models = Models::default();
    for (width, row) in FREQ.iter().enumerate() {
        for (index, freq) in row.iter().enumerate() {
            let model = Model::new(&freq[..width + 2]).expect("silicon-rans model");
            models.insert(index as u8, model);
        }
    }
    models
}""")


if __name__ == "__main__":
    main(sys.argv[1])
